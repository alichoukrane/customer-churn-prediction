"""Reusable preprocessing utilities for training and inference."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from utils.config import (
    DATA_PATH,
    IDENTIFIER_COLUMN_HINTS,
    NEGATIVE_TARGET_VALUES,
    POSITIVE_TARGET_VALUES,
    TARGET_COLUMN,
    TARGET_COLUMN_CANDIDATES,
)


NUMERIC_TEXT_THRESHOLD = 0.90


@dataclass(frozen=True)
class TrainingFrame:
    """Clean training inputs and schema metadata."""

    features: pd.DataFrame
    target: pd.Series
    target_column: str
    dropped_columns: list[str]
    duplicate_rows_removed: int
    target_rows_removed: int


def load_dataset(dataset_path: Path = DATA_PATH) -> pd.DataFrame:
    """Load the real churn dataset from disk, failing loudly if absent."""
    if not dataset_path.exists():
        raise FileNotFoundError(
            f"Dataset not found at {dataset_path}. Place a real churn.csv file in "
            "the data directory before training. Synthetic data is intentionally "
            "not generated by this project."
        )

    try:
        data = pd.read_csv(dataset_path)
    except pd.errors.EmptyDataError as exc:
        raise ValueError(
            f"Dataset at {dataset_path} is empty. Replace it with a real churn CSV."
        ) from exc

    if data.empty:
        raise ValueError(
            f"Dataset at {dataset_path} has no rows. Replace it with a real churn CSV."
        )
    return data


def infer_target_column(data: pd.DataFrame, target_column: str | None = TARGET_COLUMN) -> str:
    """Infer or validate the target column used for churn labels."""
    if target_column:
        if target_column not in data.columns:
            raise ValueError(
                f"Configured target column '{target_column}' was not found. "
                f"Available columns: {list(data.columns)}"
            )
        return target_column

    for candidate in TARGET_COLUMN_CANDIDATES:
        if candidate in data.columns:
            return candidate

    raise ValueError(
        "Could not infer the churn target column. Set CHURN_TARGET_COLUMN or pass "
        "--target-column when running src/train.py."
    )


def normalize_binary_target(raw_target: pd.Series) -> pd.Series:
    """Convert common churn target formats into 0=Stay and 1=Leave."""
    target = raw_target.copy()
    non_null = target.dropna()
    unique_values = list(pd.unique(non_null))

    if len(unique_values) != 2:
        raise ValueError(
            "The churn target must be binary after removing missing values. "
            f"Found {len(unique_values)} unique values: {unique_values}"
        )

    if pd.api.types.is_numeric_dtype(non_null):
        sorted_values = sorted(unique_values)
        mapping = {sorted_values[0]: 0, sorted_values[-1]: 1}
        return target.map(mapping).astype("Int64")

    normalized = target.astype(str).str.strip().str.lower()
    unique_normalized = set(normalized.dropna().unique())

    if unique_normalized <= POSITIVE_TARGET_VALUES | NEGATIVE_TARGET_VALUES:
        return normalized.map(
            lambda value: 1
            if value in POSITIVE_TARGET_VALUES
            else 0
            if value in NEGATIVE_TARGET_VALUES
            else np.nan
        ).astype("Int64")

    positive_candidates = [
        value
        for value in unique_normalized
        if any(token in value for token in ("churn", "leave", "left", "exit", "attrit"))
    ]
    if len(positive_candidates) == 1:
        positive = positive_candidates[0]
        return normalized.map(lambda value: 1 if value == positive else 0).astype("Int64")

    raise ValueError(
        "Unable to infer which target value represents churn. Use values such as "
        "Yes/No, 1/0, Churn/Stay, Exited/Active, or update POSITIVE_TARGET_VALUES."
    )


def _looks_like_identifier(column: str, values: pd.Series) -> bool:
    normalized_name = column.lower().replace(" ", "").replace("-", "_")
    has_id_name = any(hint == normalized_name or hint in normalized_name for hint in IDENTIFIER_COLUMN_HINTS)
    if not has_id_name:
        return False

    non_null_count = values.dropna().shape[0]
    if non_null_count == 0:
        return False
    unique_ratio = values.nunique(dropna=True) / non_null_count
    return unique_ratio >= 0.90


def normalize_feature_types(features: pd.DataFrame) -> pd.DataFrame:
    """Clean feature dtypes before sklearn column selection.

    CSV datasets often store numeric fields as text when a few blank strings
    are present. This converts those numeric-like columns back to numbers and
    keeps true categorical columns as clean string/object values.
    """
    normalized = features.copy()

    for column in normalized.columns:
        if pd.api.types.is_numeric_dtype(normalized[column]):
            continue

        cleaned = normalized[column].replace(r"^\s*$", np.nan, regex=True)
        numeric_values = pd.to_numeric(cleaned, errors="coerce")
        non_missing_count = int(cleaned.notna().sum())

        if non_missing_count == 0:
            normalized[column] = cleaned
            continue

        numeric_ratio = float(numeric_values.notna().sum() / non_missing_count)
        if numeric_ratio >= NUMERIC_TEXT_THRESHOLD:
            normalized[column] = numeric_values
        else:
            normalized[column] = cleaned

    return normalized


def prepare_training_frame(
    data: pd.DataFrame,
    target_column: str | None = None,
) -> TrainingFrame:
    """Clean data, remove leakage-prone identifiers, and split X/y."""
    resolved_target = infer_target_column(data, target_column)

    duplicate_count = int(data.duplicated().sum())
    cleaned = data.drop_duplicates().copy()

    target_missing_count = int(cleaned[resolved_target].isna().sum())
    cleaned = cleaned.dropna(subset=[resolved_target]).copy()
    y = normalize_binary_target(cleaned[resolved_target])

    valid_target_mask = y.notna()
    target_rows_removed = target_missing_count + int((~valid_target_mask).sum())
    cleaned = cleaned.loc[valid_target_mask].copy()
    y = y.loc[valid_target_mask].astype(int)

    features = cleaned.drop(columns=[resolved_target])
    features = normalize_feature_types(features)
    dropped_columns = [
        column for column in features.columns if _looks_like_identifier(column, features[column])
    ]
    if dropped_columns:
        features = features.drop(columns=dropped_columns)

    if features.empty:
        raise ValueError("No usable feature columns remain after preprocessing.")

    return TrainingFrame(
        features=features,
        target=y,
        target_column=resolved_target,
        dropped_columns=dropped_columns,
        duplicate_rows_removed=duplicate_count,
        target_rows_removed=target_rows_removed,
    )


def get_feature_groups(features: pd.DataFrame) -> tuple[list[str], list[str]]:
    """Return numerical and categorical feature column names."""
    numeric_features = features.select_dtypes(include=["number"]).columns.tolist()
    categorical_features = [
        column for column in features.columns if column not in numeric_features
    ]
    return numeric_features, categorical_features


def make_one_hot_encoder() -> OneHotEncoder:
    """Create an sklearn-version-compatible OneHotEncoder."""
    try:
        return OneHotEncoder(handle_unknown="ignore", sparse_output=False)
    except TypeError:
        return OneHotEncoder(handle_unknown="ignore", sparse=False)


def build_preprocessor(features: pd.DataFrame) -> ColumnTransformer:
    """Build the production preprocessing graph used inside model pipelines."""
    numeric_features, categorical_features = get_feature_groups(features)

    numeric_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ]
    )

    categorical_pipeline = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("encoder", make_one_hot_encoder()),
        ]
    )

    transformers: list[tuple[str, Pipeline, list[str]]] = []
    if numeric_features:
        transformers.append(("numeric", numeric_pipeline, numeric_features))
    if categorical_features:
        transformers.append(("categorical", categorical_pipeline, categorical_features))

    return ColumnTransformer(transformers=transformers, remainder="drop")


def build_metadata(
    training_frame: TrainingFrame,
    model_name: str,
    metrics: dict[str, Any],
) -> dict[str, Any]:
    """Create JSON-serializable schema and training metadata."""
    features = training_frame.features
    numeric_features, categorical_features = get_feature_groups(features)

    numeric_summary: dict[str, dict[str, float]] = {}
    for column in numeric_features:
        series = pd.to_numeric(features[column], errors="coerce")
        numeric_summary[column] = {
            "min": _safe_float(series.min()),
            "median": _safe_float(series.median()),
            "max": _safe_float(series.max()),
        }

    categorical_levels: dict[str, list[str]] = {}
    for column in categorical_features:
        values = features[column].dropna().astype(str)
        levels = values.value_counts().head(50).index.tolist()
        categorical_levels[column] = levels

    return {
        "target_column": training_frame.target_column,
        "feature_columns": features.columns.tolist(),
        "numeric_features": numeric_features,
        "categorical_features": categorical_features,
        "categorical_levels": categorical_levels,
        "numeric_summary": numeric_summary,
        "dropped_columns": training_frame.dropped_columns,
        "selected_model": model_name,
        "metrics": metrics,
        "class_labels": {"0": "Stay", "1": "Leave"},
        "prediction_threshold": 0.5,
    }


def _safe_float(value: Any) -> float:
    if pd.isna(value):
        return 0.0
    return float(value)
